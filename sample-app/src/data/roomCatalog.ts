export const buildingCatalog: ReadonlyArray<BuildingCatalogEntry> = buildingsRaw

const buildingByCode = new Map(buildingCatalog.map((b) => [b.code.toUpperCase(), b] as const))

const roomsByBuilding = Map.groupBy(roomsRaw, (r) => r.buildingCode.toUpperCase())
for (const rooms of roomsByBuilding.values()) {
  rooms.sort((a, b) => a.roomCode.localeCompare(b.roomCode))
}

const roomByKey = new Map(
  roomsRaw.map((r) => [`${r.buildingCode.toUpperCase()}::${r.roomCode.toUpperCase()}`, r] as const),
)

export function getBuildingLabel(code: string | null | undefined): string {
  if (!code) return 'Nezařazené'
  const n = code.toUpperCase()
  return buildingByCode.has(n) ? `Budova ${n}` : code
}

export function getRoomsForBuilding(
  code: string | null | undefined,
): ReadonlyArray<RoomCatalogEntry> {
  return (code && roomsByBuilding.get(code.toUpperCase())) || []
}

export function normalizeRoomInput(buildingCode: string | null | undefined, input: string): string {
  const trimmed = input.trim()
  if (!buildingCode) return trimmed
  const prefix = `${buildingCode.toUpperCase()}-`
  return trimmed.toUpperCase().startsWith(prefix) ? trimmed.slice(prefix.length).trim() : trimmed
}

export function findRoomCatalogEntry(
  buildingCode: string | null | undefined,
  roomNameOrCode: string | null | undefined,
): RoomCatalogEntry | null {
  if (!buildingCode || !roomNameOrCode) return null
  const b = buildingCode.toUpperCase()
  const r = normalizeRoomInput(b, roomNameOrCode).toUpperCase()
  return (r && roomByKey.get(`${b}::${r}`)) || null
}

export function sortBuildingCodes(codes: ReadonlyArray<string>): ReadonlyArray<string> {
  const order = new Map(buildingCatalog.map((b, i) => [b.code.toUpperCase(), i]))
  return [...codes].sort((a, b) => {
    const ai = order.get(a.toUpperCase())
    const bi = order.get(b.toUpperCase())
    if (ai != null && bi != null) return ai - bi
    if (ai != null) return -1
    if (bi != null) return 1
    return a.toUpperCase().localeCompare(b.toUpperCase())
  })
}
